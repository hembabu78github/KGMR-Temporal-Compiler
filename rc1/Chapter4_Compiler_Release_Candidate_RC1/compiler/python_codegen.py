import hashlib,json,re
from pathlib import Path

def _canon(x):
    return json.dumps(x,sort_keys=True,separators=(",",":"),ensure_ascii=False)

def semantic_fp(spec):
    return hashlib.sha256(_canon(spec).encode("utf-8")).hexdigest()

def module_name(candidate_mr_id):
    return "mr_"+re.sub(r"[^A-Za-z0-9_]","_",candidate_mr_id.lower())

def derive_control(m):
    reasons=[]
    if m.get("validation_status")!="VALID":
        reasons.append("C4_013_SPEC_NOT_VALID")
    if m.get("upstream_exception_system_action")!="PROCEED":
        reasons.append("C4_010_EXCEPTION_CONTROL_"+str(m.get("upstream_exception_system_action")))
    if m.get("upstream_temporal_system_action")!="PROCEED":
        reasons.append("C4_011_TEMPORAL_CONTROL_"+str(m.get("upstream_temporal_system_action")))
    if m.get("upstream_temporal_truth")!="TRUE":
        reasons.append("C4_011_TEMPORAL_TRUTH_"+str(m.get("upstream_temporal_truth")))
    if m.get("c4_012_conflict_ids"):
        reasons.append("C4_012_UNRESOLVED_CONFLICT_RECORD")
    return {
      "execution_gate":"PROCEED" if not reasons else "ABSTAIN",
      "blocking_reasons":sorted(set(reasons)),
      "fixture_control_status":m.get("fixture_control_status","SOFTWARE_VALIDATION_ONLY"),
      "candidate_key":m["candidate_key"],
      "semantic_spec_fingerprint":m["semantic_spec_fingerprint"],
    }

def render_module(spec,control):
    sj=json.dumps(spec,sort_keys=True,separators=(",",":"),ensure_ascii=False)
    cj=json.dumps(control,sort_keys=True,separators=(",",":"),ensure_ascii=False)
    lines=[
      "# Auto-generated by C4-014-R1.0. Do not hand edit.",
      "import json as _json",
      "from runtime.executable_runtime import apply_transformation as _transform",
      "from runtime.executable_runtime import evaluate_oracle as _oracle",
      "from runtime.executable_runtime import execute_mr as _execute",
      "",
      "_SPEC_JSON = "+repr(sj),
      "_CONTROL_JSON = "+repr(cj),
      "SPEC = _json.loads(_SPEC_JSON)",
      "CONTROL = _json.loads(_CONTROL_JSON)",
      "",
      "def transform(source_case, execution_context=None, runtime_config=None):",
      "    return _transform(SPEC, source_case, execution_context, runtime_config)",
      "",
      "def oracle(source_output, followup_output, oracle_context=None, runtime_config=None):",
      "    return _oracle(SPEC, source_output, followup_output, oracle_context, runtime_config)",
      "",
      "def execute(source_case, cds_callable, execution_context=None, oracle_context=None, runtime_config=None):",
      "    return _execute(SPEC, CONTROL, source_case, cds_callable, execution_context, oracle_context, runtime_config)",
      ""
    ]
    return "\n".join(lines)

def generate_modules(spec_dir,manifest_rows,out_dir):
    out=Path(out_dir); out.mkdir(parents=True,exist_ok=True)
    rows=[]
    for m in sorted(manifest_rows,key=lambda x:x["candidate_mr_id"]):
        sp=Path(spec_dir)/f"{m['candidate_mr_id']}.json"
        spec=json.loads(sp.read_text(encoding="utf-8"))
        actual=semantic_fp(spec)
        if actual!=m["semantic_spec_fingerprint"]:
            raise ValueError("semantic fingerprint mismatch for "+m["candidate_mr_id"])
        control=derive_control(m)
        name=module_name(m["candidate_mr_id"])
        path=out/f"{name}.py"
        path.write_text(render_module(spec,control),encoding="utf-8",newline="\n")
        rows.append({
          "candidate_mr_id":m["candidate_mr_id"],
          "candidate_key":m["candidate_key"],
          "operator_id":m["operator_id"],
          "module_name":name,
          "module_path":path.name,
          "execution_gate":control["execution_gate"],
          "blocking_reasons":control["blocking_reasons"],
          "semantic_spec_fingerprint":actual,
          "generated_python_sha256":hashlib.sha256(path.read_bytes()).hexdigest()
        })
    (out/"__init__.py").write_text("",encoding="utf-8",newline="\n")
    return rows
